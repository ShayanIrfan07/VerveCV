export function normalizeTermKey(term: string): string {
  return term
    .trim()
    .replace(/['’]s$/iu, "")
    .toLowerCase();
}

export function isTechnicalTerm(token: string): boolean {
  const normalized = normalizeTermKey(token);
  if (normalized.length === 0) {
    return false;
  }
  if (ALLOWLIST_SET.has(normalized)) {
    return true;
  }
  if (/^[a-z][a-z0-9-]*\.(?:js|ts|mjs|cjs|jsx|tsx|py|rb|go|rs|io|ai|dev|sh|css|vue|svelte)$/u.test(normalized)) {
    return true;
  }
  return false;
}

export function isProductiveHyphenPrefix(prefix: string): boolean {
  return PRODUCTIVE_HYPHEN_PREFIXES.has(prefix.toLowerCase());
}
